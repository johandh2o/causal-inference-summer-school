@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## Data-generating mechanism

    We generate \(W=(W_1,\ldots,W_5)\), then treatment, then the observed outcome \(Y=Y^A\).

    \[
    W_j\sim N(0,1),\qquad j=1,\ldots,5.
    \]

    Treatment assignment is confounded:

    \[
    \operatorname{logit}\{\varpi_\lambda(W)\}
    =\lambda\Big[-0.10
    +0.80W_1
    -0.90W_2
    +0.70W_3
    +0.70W_1W_2
    -0.60\mathbb{I}(W_4>0)
    +0.50\sin(W_5)\Big].
    \]

    Larger \(\lambda\) means **more lack of overlap**.

    The potential outcomes are generated by

    \[
    Y^a=\mu_0(W)+a\tau(W)+\varepsilon,
    \qquad \varepsilon\sim N(0,1),
    \]

    where

    \[
    \begin{aligned}
    \mu_0(W)
    &=1+1.60\sin(W_1)+1.20W_2^2-1.20W_3
    +1.10W_4W_5 \\
    &\hspace{1.0cm}+0.80\mathbb{I}(W_1>0)W_2-0.70\cos(W_5),\\[0.4em]
    \tau(W)
    &=1+0.80W_1-0.70W_2+0.80\mathbb{I}(W_3>0)
    +0.60\sin(W_4) \\
    &\hspace{1.0cm}+0.50W_2W_5-0.40W_1W_4.
    \end{aligned}
    \]

    Therefore, the true conditional treatment effect is \(\tau(W)=Y^1-Y^0\), and the target is \(\psi=\mathbb{E}\{\tau(W)\}\).
    """)
    return


@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## Estimators compared in this lab

    **1. Misspecified plug-in.** We intentionally fit the wrong outcome regression:

    \[
    Q^{\mathrm{mis}}(w,a;\beta)
    =\beta_0+\beta_Aa+\beta_1w_1+\beta_2w_2.
    \]

    This model omits \(W_3,W_4,W_5\), nonlinear terms, interactions, and all treatment-effect heterogeneity.

    **2. Naïve AIPW.** We fit a flexible regression tree for \(Q(w,a)\), but evaluate \(\widehat Q(W_i,A_i)\) on the **same observations used to train it**:

    \[
    \widehat\psi_{\mathrm{AIPW}}
    =n^{-1}\sum_{i=1}^n\left[
    \widehat Q(W_i,1)-\widehat Q(W_i,0)
    +\left(\frac{A_i}{\widehat{\pi}(1\mid W_i)}
    -\frac{1-A_i}{\widehat{\pi}(0\mid W_i)}\right)\{Y_i-\widehat Q(W_i,A_i)\}
    \right].
    \]

    **3. DML.** We use the same score, but \(\widehat Q(W_i,A_i)\) is computed out-of-fold. The observation \(i\) is not used to train its own nuisance prediction.

    **4. TMLE.** Starting from the same cross-fitted nuisance predictions as DML, we make a least-squares targeting update:

    \[
    \widehat Q^\star(W,A)=\widehat Q(W,A)+\widehat\epsilon H(W,A),
    \qquad
    H(W,A)=\frac{A}{\widehat{\pi}(1\mid W)}-\frac{1-A}{\widehat{\pi}(0\mid W)},
    \]

    with

    \[
    \widehat\epsilon
    =\frac{\sum_{i=1}^n\left[H(W_i,A_i)\{Y_i-\widehat Q(W_i,A_i)\}\right]}
    {\sum_{i=1}^n\{H(W_i,A_i)^2\}}.
    \]

    The propensity-score lever lets you compare two options. The first option uses the true \(\varpi(W)\) from the simulator, which isolates the effect of overfitting in \(Q\). The second option estimates a deliberately misspecified propensity score by fitting the logistic model

    \[
    \operatorname{logit}\{\varpi^{\mathrm{mis}}(W;\alpha)\}
    =\alpha_0+\alpha_1W_1+\alpha_2W_2+\alpha_{12}W_1W_2.
    \]

    This model ignores \(W_3,W_4,W_5\), even though those variables affect the true treatment assignment above. When this option is selected, every estimator that uses inverse-propensity weights uses this misspecified \(\widehat\varpi^{\mathrm{mis}}(W)\).
    """)
    return


