@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## Data-generating mechanism

    We generate \(W=(W_1,\ldots,W_5)\), then treatment, then the observed outcome \(Y=Y^A\).

    \[
    W_j\sim N(0,1),\qquad j=1,\ldots,5.
    \]

    Treatment assignment is confounded and can have weak overlap:

    \[
    \operatorname{logit}\{\varpi_{\lambda}(W)\}
    =\lambda\Big[-0.10
    +0.80W_1
    -0.90W_2
    +0.70W_3
    +0.70W_1W_2
    -0.60\mathbb{I}(W_4>0)
    +0.50\sin(W_5)\Big].
    \]

    Larger \(\lambda\) means **more lack of overlap**. When \(\lambda\) is large, some units have \(\varpi(W)\) close to 0 or 1.

    The potential outcomes are generated by

    \[
    Y^a=\mu_0(W;\rho)+a\tau(W;\rho)+\varepsilon,
    \qquad \varepsilon\sim N(0,1),
    \]

    where \(\rho\) controls the **misspecification pressure** faced by simple outcome regressions:

    \[
    \begin{aligned}
    \mu_0(W;\rho)
    &=1+
    \rho\Big\{1.80\sin(W_1)+1.30W_2^2-1.50W_3
    +1.10W_4W_5 \\
    &\hspace{2.7cm}+0.80\mathbb{I}(W_1>0)W_2-0.80\cos(W_5)\Big\},\\[0.4em]
    \tau(W;\rho)
    &=1+
    \rho\Big\{0.80W_1-0.70W_2+0.90\mathbb{I}(W_3>0)
    +0.60\sin(W_4) \\
    &\hspace{2.7cm}+0.50W_2W_5-0.40W_1W_4\Big\}.
    \end{aligned}
    \]

    Therefore, the true conditional treatment effect is \(\tau(W)=Y^1-Y^0\), and the target is \(\psi=\mathbb{E}\{\tau(W)\}\).
    """)
    return


@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## The two deliberately misspecified outcome regressions

    The lab fits two outcome models. Both are intentionally wrong, but in different ways.

    **Misspecified model 1: simple linear regression**

    \[
    Q_1^{\text{mis}}(w,a;\beta)
    =\beta_0+\beta_A a+\beta_1w_1+\beta_2w_2.
    \]

    This model omits \(W_3,W_4,W_5\), all nonlinear terms, all interactions, and all treatment-effect heterogeneity.

    **Misspecified model 2: partial interactions but missing important confounders**

    \[
    Q_2^{\text{mis}}(w,a;\beta)
    =\beta_0+\beta_Aa+\beta_1w_1+\beta_2w_2
    +\beta_{12}w_1w_2+\beta_{A1}aw_1+\beta_{A2}aw_2.
    \]

    This model looks more sophisticated, but it still omits the important confounder \(W_3\), the terms involving \(W_4,W_5\), the nonlinear terms \(\sin(W_1),W_2^2,\cos(W_5),\sin(W_4)\), and several treatment-effect modifiers.

    We compare four estimators:

    \[
    \widehat\psi_{\text{plug-in},1},\qquad
    \widehat\psi_{\text{plug-in},2},\qquad
    \widehat\psi_{\text{AIPW},1},\qquad
    \widehat\psi_{\text{AIPW},2}.
    \]

    For both AIPW estimators, \(\widehat\varpi(W)\) is set to the **correct propensity score from the simulator**, with a mild numerical truncation at 0.005 and 0.995. This isolates the double-robustness idea: even if \(Q\) is badly wrong, AIPW can still recover \(\psi\) when \(\varpi\) is correct and overlap is not too weak.
    """)
    return


