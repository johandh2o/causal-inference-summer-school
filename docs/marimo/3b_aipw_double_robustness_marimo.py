@app.cell(hide_code=True)
def _(LinearRegression, np, pd, plt):
    def expit(x):
        return 1.0 / (1.0 + np.exp(-x))

    def generate_data(n, overlap_lambda=1.0, misspec_rho=1.5, seed=1):
        rng = np.random.default_rng(seed)
        W = rng.normal(size=(n, 5))
        W1, W2, W3, W4, W5 = W.T

        eta = overlap_lambda * (
            -0.10
            + 0.80 * W1
            - 0.90 * W2
            + 0.70 * W3
            + 0.70 * W1 * W2
            - 0.60 * (W4 > 0)
            + 0.50 * np.sin(W5)
        )
        varpi = expit(eta)
        A = rng.binomial(1, varpi)

        mu0 = 1.0 + misspec_rho * (
            1.80 * np.sin(W1)
            + 1.30 * W2**2
            - 1.50 * W3
            + 1.10 * W4 * W5
            + 0.80 * (W1 > 0) * W2
            - 0.80 * np.cos(W5)
        )
        tau = 1.0 + misspec_rho * (
            0.80 * W1
            - 0.70 * W2
            + 0.90 * (W3 > 0)
            + 0.60 * np.sin(W4)
            + 0.50 * W2 * W5
            - 0.40 * W1 * W4
        )
        eps = rng.normal(scale=1.0, size=n)
        Y_zero = mu0 + eps
        Y_one = mu0 + tau + eps
        Y = mu0 + A * tau + eps

        df = pd.DataFrame(W, columns=[f"W{j}" for j in range(1, 6)])
        df["A"] = A
        df["Y"] = Y
        df["Y_zero_true"] = Y_zero
        df["Y_one_true"] = Y_one
        df["tau_true"] = tau
        df["varpi_true"] = varpi
        return df

    def design_Q(df, a_value=None, q_model="Q1"):
        d = df.copy()
        if a_value is not None:
            d["A"] = a_value
        W1 = d["W1"].to_numpy()
        W2 = d["W2"].to_numpy()
        A = d["A"].to_numpy()
        if q_model == "Q1":
            return np.column_stack([A, W1, W2])
        if q_model == "Q2":
            return np.column_stack([A, W1, W2, W1 * W2, A * W1, A * W2])
        raise ValueError("q_model must be either 'Q1' or 'Q2'")

    def design_varpi(df):
        W1 = df["W1"].to_numpy()
        W2 = df["W2"].to_numpy()
        W3 = df["W3"].to_numpy()
        W4 = df["W4"].to_numpy()
        W5 = df["W5"].to_numpy()
        return np.column_stack([W1, W2, W3, W1 * W2, (W4 > 0), np.sin(W5)])

    def fit_Q_and_predict(df, q_model):
        model = LinearRegression()
        X = design_Q(df, q_model=q_model)
        y = df["Y"].to_numpy()
        model.fit(X, y)
        q1 = model.predict(design_Q(df, a_value=1, q_model=q_model))
        q0 = model.predict(design_Q(df, a_value=0, q_model=q_model))
        return q1, q0

    def plugin_estimate(df, q_model):
        q1, q0 = fit_Q_and_predict(df, q_model)
        return float(np.mean(q1 - q0))

    def fit_correct_varpi(df):
        # Pedagogical choice: use the correct propensity score from the simulator.
        # The truncation is only for numerical stability when the overlap lever is large.
        return np.clip(df["varpi_true"].to_numpy(), 0.005, 0.995)

    def aipw_estimate(df, q_model, varpi_hat):
        q1, q0 = fit_Q_and_predict(df, q_model)
        A = df["A"].to_numpy()
        Y = df["Y"].to_numpy()
        phi = q1 - q0 + A / varpi_hat * (Y - q1) - (1 - A) / (1 - varpi_hat) * (Y - q0)
        estimate = float(np.mean(phi))
        se = float(np.std(phi, ddof=1) / np.sqrt(len(df)))
        return estimate, se, phi

    def bootstrap_plugin_ci(df, q_model, B=60, seed=123):
        rng = np.random.default_rng(seed)
        n = len(df)
        estimates = []
        for _ in range(B):
            idx = rng.integers(0, n, size=n)
            boot = df.iloc[idx].reset_index(drop=True)
            estimates.append(plugin_estimate(boot, q_model))
        estimates = np.asarray(estimates)
        se = float(np.std(estimates, ddof=1))
        lo, hi = np.quantile(estimates, [0.025, 0.975])
        return se, float(lo), float(hi)

    def run_all_estimators(n, overlap_lambda, misspec_rho, seed):
        df = generate_data(
            int(n),
            overlap_lambda=float(overlap_lambda),
            misspec_rho=float(misspec_rho),
            seed=int(seed),
        )
        true_psi = float(np.mean(df["tau_true"]))
        varpi_hat = fit_correct_varpi(df)

        rows = []
        for label, q_model in [
            ("Plug-in 1: simple linear Q", "Q1"),
            ("Plug-in 2: partial interactions Q", "Q2"),
        ]:
            est = plugin_estimate(df, q_model)
            se, lo, hi = bootstrap_plugin_ci(df, q_model, B=60, seed=int(seed) + (11 if q_model == "Q1" else 29))
            rows.append({
                "estimator": label,
                "estimate": est,
                "SE": se,
                "CI lower": lo,
                "CI upper": hi,
                "bias": est - true_psi,
                "uncertainty": "small bootstrap",
            })

        for label, q_model in [
            ("AIPW 1: Q1 + correct varpi", "Q1"),
            ("AIPW 2: Q2 + correct varpi", "Q2"),
        ]:
            est, se, _ = aipw_estimate(df, q_model, varpi_hat)
            rows.append({
                "estimator": label,
                "estimate": est,
                "SE": se,
                "CI lower": est - 1.96 * se,
                "CI upper": est + 1.96 * se,
                "bias": est - true_psi,
                "uncertainty": "EIF SE",
            })

        results = pd.DataFrame(rows)
        varpi_summary = pd.DataFrame({
            "quantity": [
                "true psi",
                "treatment prevalence",
                "min true varpi(W)",
                "5% true varpi(W)",
                "median true varpi(W)",
                "95% true varpi(W)",
                "max true varpi(W)",
            ],
            "value": [
                true_psi,
                float(df["A"].mean()),
                float(df["varpi_true"].min()),
                float(df["varpi_true"].quantile(0.05)),
                float(df["varpi_true"].median()),
                float(df["varpi_true"].quantile(0.95)),
                float(df["varpi_true"].max()),
            ],
        })
        return df, results, varpi_summary, true_psi

    def make_ci_plot(results, true_psi):
        plot_df = results.copy()
        y = np.arange(len(plot_df))
        x = plot_df["estimate"].to_numpy()
        lo = plot_df["CI lower"].to_numpy()
        hi = plot_df["CI upper"].to_numpy()
        xerr = np.vstack([x - lo, hi - x])
        fig, ax = plt.subplots(figsize=(8.2, 4.8))
        ax.errorbar(x, y, xerr=xerr, fmt="o", capsize=4, linewidth=1.5)
        ax.axvline(true_psi, linestyle="--", linewidth=1.2)
        ax.set_yticks(y)
        ax.set_yticklabels(plot_df["estimator"])
        ax.set_xlabel("ATE estimate with 95% interval")
        ax.set_title("AIPW repairs misspecified Q when varpi is correct")
        ax.grid(axis="x", alpha=0.25)
        fig.tight_layout()
        return fig

    def diagnostic_message(results, overlap_lambda, misspec_rho):
        plugin_bias = results.loc[results["estimator"].str.startswith("Plug-in"), "bias"].abs().mean()
        aipw_bias = results.loc[results["estimator"].str.startswith("AIPW"), "bias"].abs().mean()
        lines = []
        lines.append(
            f"Average absolute plug-in bias: {plugin_bias:.3f}. Average absolute AIPW bias: {aipw_bias:.3f}."
        )
        if aipw_bias < plugin_bias:
            lines.append(
                "This is the intended double-robustness pattern: Q is badly misspecified, but the correctly specified propensity score model helps the AIPW estimator move toward ψ."
            )
        else:
            lines.append(
                "Here AIPW did not dominate the plug-ins in this one finite sample. Discuss variance, weak overlap, and finite-sample instability rather than treating double robustness as a deterministic finite-sample guarantee."
            )
        if float(overlap_lambda) >= 1.75:
            lines.append(
                "The overlap parameter is large. Some estimated weights can become large, so AIPW may have wider intervals and more finite-sample variability."
            )
        if float(misspec_rho) >= 2.25:
            lines.append(
                "The outcome regression is severely nonlinear. The two plug-ins are expected to be badly biased because their Q-models miss central parts of the true assignment mechanism."
            )
        return "\n\n".join(lines)

    return diagnostic_message, make_ci_plot, run_all_estimators


@app.cell(hide_code=True)
def _(
    lab_misspec,
    lab_n,
    lab_overlap,
    lab_run_button,
    lab_seed,
    mo,
    run_all_estimators,
):
    mo.stop(not lab_run_button.value, mo.md("Press **Run the four estimators** after selecting the three levers."))
    lab_df, lab_results, lab_varpi_summary, lab_true_psi = run_all_estimators(
        n=lab_n.value,
        overlap_lambda=lab_overlap.value,
        misspec_rho=lab_misspec.value,
        seed=lab_seed.value,
    )
    return lab_results, lab_true_psi, lab_varpi_summary


@app.cell(hide_code=True)
def _(
    diagnostic_message,
    lab_misspec,
    lab_overlap,
    lab_results,
    lab_true_psi,
    lab_varpi_summary,
    make_ci_plot,
    mo,
):
    fig = make_ci_plot(lab_results, lab_true_psi)
    display_results = lab_results.copy()
    display_results["covers true psi"] = (
        (display_results["CI lower"] <= lab_true_psi) &
        (lab_true_psi <= display_results["CI upper"])
    )
    mo.vstack([
        mo.md("## Results"),
        mo.md(r"The dashed vertical line in the plot is the finite-sample truth, \(n^{-1}\sum_i \tau(W_i)\)."),
        fig,
        display_results.round(3),
        mo.md("## Propensity-score and overlap diagnostics"),
        lab_varpi_summary.round(3),
        mo.md("## Diagnostic interpretation"),
        mo.md(diagnostic_message(lab_results, lab_overlap.value, lab_misspec.value)),
    ])
    return


